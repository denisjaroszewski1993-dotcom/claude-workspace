export function meaningOf(index: number): LabelMeaning | undefined {
  const single = SINGLE[index];
  if (single) return single;
  for (const [from, to, meaning] of RANGES) {
    if (index >= from && index <= to) return meaning;
  }
  return undefined;
}

/** Deutsche Bezeichnung, sonst der erste englische Name der Klasse. */
export function labelName(index: number, englishName: string): string {
  return meaningOf(index)?.de ?? englishName.split(",")[0].trim();
}
